#!/usr/bin/env bash
# PreToolUse (Edit|Write): blocks edits to files that must not be hand-edited.
# Exit 2 = block, and the message on stderr is shown to Claude.
set -euo pipefail

file=$(python3 -c 'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("file_path",""))')
rel=${file#"$CLAUDE_PROJECT_DIR"/}

case "$rel" in
  .env)
    echo "Blocked: .env holds real secrets. Ask the user to change it, and update .env.example with a placeholder." >&2
    exit 2 ;;
  apps/api/uv.lock|apps/mobile/package-lock.json)
    echo "Blocked: lock files are written by 'uv add/sync' or 'npx expo install', not by hand." >&2
    exit 2 ;;
  apps/mobile/src/api/schema.d.ts)
    echo "Blocked: generated from OpenAPI. Run scripts/gen-api-types.sh instead." >&2
    exit 2 ;;
  docs/database.md|docs/api/endpoints.md|docs/api/errors.md|docs/api/.endpoint-tables.json)
    echo "Blocked: generated doc. Change the code, then run scripts/gen-docs.sh." >&2
    exit 2 ;;
  docs/api/*.md)
    if [ "$rel" != "docs/api/README.md" ]; then
      echo "Blocked: generated API doc. Change the code, then run scripts/gen-docs.sh." >&2
      exit 2
    fi ;;
  apps/api/migrations/versions/*)
    # Applied migrations are history: only brand-new files may be written
    if [ -f "$file" ] && git -C "$CLAUDE_PROJECT_DIR" ls-files --error-unmatch "$rel" >/dev/null 2>&1; then
      echo "Blocked: $rel is a committed migration. Create a new revision instead (see /db-migration)." >&2
      exit 2
    fi ;;
  apps/mobile/ios/*|apps/mobile/android/*)
    echo "Blocked: native folders are generated by Expo. Configure app.json / config plugins instead." >&2
    exit 2 ;;
esac
exit 0
